/** One file of the digest. Paths use forward slashes and are relative to the digest folder. */
export interface DigestFile {
  path: string;
  content: string;
}

interface Entry {
  /** Path of the argument file from the workspace root. */
  file: string;
  /** Path of its page in the digest. */
  page: string;
  loaded: LoadedFile;
  analysis?: Analysis;
  res?: Resolution;
}

const slash = (path: string): string => path.split(sep).join('/');
const code = (id: string): string => `\`${id}\``;
const ids = (list: readonly string[]): string => list.map(code).join(', ');
/** Text on one line, exactly as written apart from line breaks. Pinned-term markers are kept. */
const one = (text: string): string => text.replace(/\s+/g, ' ').trim();
const count = (n: number, noun: string, many = `${noun}s`): string => `${n} ${n === 1 ? noun : many}`;

function built(root: string): string {
  const sha = isRepo(root) ? tryGit(root, ['rev-parse', '--short=7', 'HEAD']) : undefined;
  const date = sha ? tryGit(root, ['log', '-1', '--format=%cs']) : undefined;
  return `Generated by \`argmap digest\`${sha ? ` from commit ${sha}${date ? ` (${date})` : ''}` : ''}. Do not edit: change the source files and generate it again.`;
}

function settlements(a: Analysis): string {
  const open = a.cruxes.cruxes.length;
  if (open === 0) return 'none open';
  const t = a.cruxes.tally;
  if (!t) return `${open} open, too many to count every way of settling them`;
  return `${open} open. Of the ${t.total} ways to settle them the conclusion stands in ${t.stands}, falls in ${t.falls}, stays contested in ${t.contested}`;
}

/* ---------- Parts of a claim ---------- */

const KIND_NOTE: Record<Step['kind'], string> = {
  adjudicate: 'reviewers disagree, so it needs a decision',
  answer: 'a reviewer rejected it, or a test of it failed: revise it, replace it or let it fall',
  resolve: 'a test is waiting for its outcome: check it and record what was found',
  accept: 'someone set a test; until a voucher accepts it, a failure cannot knock the claim out',
  predict: 'specific but never tested: before looking anything up, record what you expect to find',
  refine: 'a bet too vague to check; what is vague is listed under the claim',
  check: 'specific but unchecked, or trusted beyond its evidence: find a source or a test',
  settle: 'an open dispute: find evidence for one side, or sharpen both until they stop conflicting',
  review: 'nobody has reviewed it',
};

/** What a status change does to the conclusion, as a verb. */
const VERB: Record<Status, string> = { stands: 'stands', falls: 'falls', contested: 'becomes contested' };

/** The engine's messages put a claim's label or id in double quotes. The digest names every claim by its id, in backticks. */
function named(text: string, arg: Argument): string {
  const names = [...arg.claims.values()].flatMap((c) => [[c.label, c.id], [c.id, c.id]] as [string, string][]).sort((x, y) => y[0].length - x[0].length);
  for (const [name, id] of names) text = text.split(`"${name}"`).join(code(id));
  return text;
}

/**
 * Why a claim has its status. The engine's sentence names claims by label and
 * repeats the status and the trust; here claims are named by id and neither is repeated.
 */
function why(arg: Argument, a: Analysis, id: string): string {
  let text = reason(arg, a.statuses, new Set(), id)
    .replace(/^Contested(: |\.$)/, '')
    .replace(/^Held as a bet \([^)]*\)\.\s*/, '');
  text = named(text, arg);
  return text === '' ? '' : `. ${text.charAt(0).toUpperCase()}${text.slice(1)}`;
}

function support(claim: Claim): string {
  if (claim.because.length === 1) return (claim.because[0] as string[]).map(code).join(' + ');
  return claim.because.map((group, i) => `line ${i + 1}: ${group.map(code).join(' + ')}`).join('; ');
}

function evidenceLines(claim: Claim): string[] {
  if (claim.evidence.length === 0) return [];
  const pro = claim.evidence.filter((e) => e.stance === 'for').length;
  const out = [`- evidence: ${pro} for, ${claim.evidence.length - pro} against, ${count(independentSources(claim), 'independent source')} for`];
  for (const e of claim.evidence) {
    const facts = [
      e.value !== undefined ? `${e.value}${e.unit ? ` ${e.unit}` : ''}` : '',
      e.sample ? `sample: ${e.sample}` : '',
      e.period ? `period: ${e.period}` : '',
      e.witness ? `witness: ${e.witness}` : '',
      e.firstHand === true ? 'first-hand' : e.firstHand === false ? 'second-hand' : '',
      e.peerReviewed === true ? 'peer reviewed' : e.peerReviewed === false ? 'not peer reviewed' : '',
      e.origin ? `origin: ${e.origin}` : '',
    ].filter((f) => f !== '');
    const fields = [`${e.stance}, ${e.kind}: ${one(e.says)}`, ...facts.map(one), `source: ${e.source ? one(e.source) : 'none given'}`];
    if (e.by) fields.push(`by ${e.by}${e.date ? `, ${e.date}` : ''}`);
    out.push(`  - ${fields.join(' | ')}`);
  }
  return out;
}

function testLines(claim: Claim): string[] {
  if (claim.predictions.length === 0) return [];
  const r = claimRecord(claim);
  const backers = vouchers(claim);
  const summary = [
    `${r.passed} passed where a failure would have knocked it out${r.passed > 0 ? ` (${r.passedFromOthers} set by someone not vouching for it; hardness ${r.bitsOthers.toFixed(1)} bits as typed by others, ${r.bitsOwn.toFixed(1)} as typed by its own vouchers)` : ''}`,
    r.passedNoRisk > 0 ? `${r.passedNoRisk} passed with nothing at risk` : '',
    `${r.failed} failed`,
    `${r.open} open`,
    r.offered > 0 ? `offered by others: ${r.offered}, accepted: ${r.offeredAccepted}` : '',
    r.withdrawn > 0 ? `withdrawn after acceptance: ${r.withdrawn}` : '',
    r.failedEarlier > 0 ? `failed under an earlier wording: ${r.failedEarlier}` : '',
    `vouched for by: ${backers.length > 0 ? backers.join(', ') : 'nobody'}`,
  ].filter((x) => x !== '');
  return [`- tests: ${summary.join('; ')}`, ...claim.predictions.map((p, i) => `  - ${one(describeTest(claim, p, i + 1))}`)];
}

function reviewLines(claim: Claim): string[] {
  const r = reviewSummary(claim);
  if (r.current.length + r.stale.length === 0) return [];
  const out = [`- review: ${r.state}${r.current.length > 0 ? ` (${r.confirms} confirm, ${r.rejects} reject)` : ''}`];
  const line = (x: Claim['reviews'][number], stale: boolean): string =>
    `  - ${x.verdict} by ${x.by} (${x.kind})${x.date ? `, ${x.date}` : ''}${stale ? ', stale: judged an earlier wording' : ''}${x.note ? `: ${one(x.note)}` : ''}`;
  out.push(...r.current.map((x) => line(x, false)), ...r.stale.map((x) => line(x, true)));
  return out;
}

function flagLines(flags: readonly Flag[]): string[] {
  return flags.map((f) => `- could be sharper [${f.code}]: ${f.message}`);
}

/* ---------- One argument ---------- */

/**
 * The structure at a glance: one claim per line with its status and id, what it
 * rests on indented under it, then what is said against it. Text is left to the
 * Claims section, which lists the claims in this same order.
 */
function outline(arg: Argument, a: Analysis): { lines: string[]; order: string[] } {
  const attackers = attackersOf(arg);
  const disputed = new Set(arg.disputes.flatMap(([x, y]) => [`${x}|${y}`, `${y}|${x}`]));
  const lines: string[] = [];
  const order: string[] = [];
  const item = (id: string, role: string, trail: readonly string[], depth: number, target = ''): void => {
    const claim = arg.claims.get(id);
    if (!claim) return;
    const repeat = order.includes(id);
    if (!repeat) order.push(id);
    const tags = [
      role === 'against' ? (disputed.has(`${id}|${target}`) ? 'in dispute with the claim above' : 'objection to the claim above') : '',
      claim.bet ? `bet: ${claim.bet.trust}` : '',
      repeat ? 'shown above' : '',
    ].filter((x) => x !== '');
    lines.push(`${'  '.repeat(depth)}- ${a.statuses.get(id) ?? 'contested'} ${code(id)}${tags.length > 0 ? ` (${tags.join('; ')})` : ''}`);
    if (repeat || trail.includes(id)) return;
    const next = [...trail, id];
    claim.because.forEach((group, i) => {
      const nested = claim.because.length > 1;
      if (nested) lines.push(`${'  '.repeat(depth + 1)}- line ${i + 1} of ${claim.because.length}, any one line is enough:`);
      for (const m of group) item(m, 'because', next, depth + (nested ? 2 : 1));
    });
    for (const att of attackers.get(id) ?? []) if (!next.includes(att)) item(att, 'against', next, depth + 1, id);
  };
  item(arg.conclusion, 'root', [], 0);
  return { lines, order };
}

/** Steps of one kind share one reason, so they are listed together, still in order of value. */
function stepLines(steps: Step[]): string[] {
  if (steps.length === 0) return ['Nothing outstanding.'];
  const out: string[] = [];
  for (const decisive of [true, false]) {
    const some = steps.filter((s) => s.decisive === decisive);
    if (some.length === 0) continue;
    if (out.length > 0) out.push('');
    out.push(decisive ? 'Can change the conclusion:' : 'Cannot change the conclusion by themselves:', '');
    for (const kind of [...new Set(some.map((s) => s.kind))]) {
      const targets = some.filter((s) => s.kind === kind).map((s) => s.claims.map(code).join(' against '));
      out.push(`- ${kind} (${KIND_NOTE[kind]}): ${targets.join(kind === 'settle' ? '; ' : ', ')}`);
    }
  }
  return out;
}

function argumentClaim(arg: Argument, a: Analysis, claim: Claim, res: Resolution | undefined): string[] {
  const id = claim.id;
  const disputes = arg.disputes.filter((pair) => pair.includes(id)).map(([x, y]) => (x === id ? y : x));
  const objectsTo = arg.attacks.filter((x) => x.from === id && !disputes.includes(x.to)).map((x) => x.to);
  const objectedBy = arg.attacks.filter((x) => x.to === id && !disputes.includes(x.from)).map((x) => x.from);
  const holdsUp = [...arg.claims.values()].filter((c) => c.because.some((g) => g.includes(id))).map((c) => c.id);
  const bet = a.bets.find((b) => b.id === id);
  const out = [`### ${id}`, '', `- status: ${a.statuses.get(id) ?? 'contested'}${why(arg, a, id)}`];
  out.push(`- kind: ${claim.bet ? `bet, trust ${claim.bet.trust}, cost ${claim.bet.cost}${claim.bet.explicit ? '' : ' (no bet written, so assumed)'}` : 'supported'}`);
  out.push(`- text: ${one(claim.text)}`);
  if (claim.because.length > 0) out.push(`- rests on: ${support(claim)}`);
  if (holdsUp.length > 0) out.push(`- holds up: ${ids(holdsUp)}`);
  if (objectsTo.length > 0) out.push(`- objects to: ${ids(objectsTo)}`);
  if (objectedBy.length > 0) out.push(`- objected to by: ${ids(objectedBy)}`);
  if (disputes.length > 0) out.push(`- in dispute with: ${ids(disputes)}`);
  if (bet) out.push(`- side: ${bet.side === 'none' ? 'neither for nor against' : bet.side === 'both' ? 'both for and against' : bet.side} the conclusion`, `- if it fails: the conclusion ${bet.decisive ? VERB[bet.conclusionIfFails] : 'is unchanged'}; ${count(bet.alsoChanges, 'other claim changes', 'other claims change')}`);
  if (claim.origin !== '') out.push(`- library: defined in ${code(claim.origin)}`);
  if (claim.bet?.note) out.push(`- stops here because: ${one(claim.bet.note)}`);
  if (claim.note) out.push(`- note: ${one(claim.note)}`);
  out.push(...flagLines(res?.flags.get(id) ?? []), ...reviewLines(claim), ...evidenceLines(claim), ...testLines(claim), '');
  return out;
}

function termLines(terms: Iterable<Term>, claims: Iterable<Claim>, where = ''): string[] {
  const all = [...claims];
  return [...terms].map((term) => {
    const pinned = all.filter((c) => termKeys(c.text).includes(term.key)).map((c) => c.id);
    return `- ${code(term.key)}: ${one(term.definition)}${term.aliases.length > 0 ? ` Also written: ${term.aliases.join(', ')}.` : ''} Pinned in${where}: ${pinned.length > 0 ? ids(pinned) : 'no claim'}.`;
  });
}

function argumentPage(root: string, entry: Entry): string {
  const { loaded } = entry;
  const arg = loaded.argument;
  const errors = loaded.issues.filter((i) => i.severity === 'error');
  const warnings = loaded.issues.filter((i) => i.severity === 'warning');
  const issue = (i: (typeof loaded.issues)[number]): string => {
    const unnamed = i.claims.filter((id) => !i.message.includes(id));
    return `- [${i.code}] ${one(arg ? named(i.message, arg) : i.message)}${unnamed.length > 0 ? ` Claims: ${ids(unnamed)}.` : ''}`;
  };
  const out = [`# ${arg ? one(arg.title) : entry.file}`, '', `Digest of ${code(entry.file)}. ${built(root)}`, ''];
  const a = entry.analysis;
  if (!arg || !a) {
    out.push('## Errors', '', 'The file does not load, so nothing is computed.', '', ...errors.map(issue), '');
    return out.join('\n');
  }
  const conclusion = arg.claims.get(arg.conclusion);
  const withEvidence = [...arg.claims.values()].filter((c) => c.evidence.length > 0);
  const reviewed = [...arg.claims.values()].filter((c) => reviewSummary(c).state !== 'unreviewed').length;
  const last = arg.log.at(-1);

  out.push('## Verdict', '');
  out.push(`- conclusion: ${code(arg.conclusion)} is ${a.conclusion}${why(arg, a, arg.conclusion)}`);
  if (conclusion) out.push(`- text: ${one(conclusion.text)}`);
  out.push(`- disputes: ${settlements(a)}`);
  if (a.cruxes.standsOnlyIf.length > 0) out.push(`- it stands only if these prevail: ${ids(a.cruxes.standsOnlyIf)}`);
  out.push(`- claims: ${arg.claims.size}, of which ${entry.res?.bets ?? 0} are bets and ${entry.res?.sharp ?? 0} of those are specific enough to check`);
  out.push(`- evidence: ${count(withEvidence.reduce((n, c) => n + c.evidence.length, 0), 'record')} on ${count(withEvidence.length, 'claim')}`);
  out.push(`- reviews: ${reviewed} of ${arg.claims.size} claims reviewed`);
  const tests = testability(arg);
  out.push(`- tests: ${tests.tested} of ${tests.bets} bets have a test of their present wording; ${tests.passed} passed, ${tests.failed} failed, ${tests.open} open; ${tests.unvouched} bets have nobody vouching for them, so no test can knock them out`);
  out.push(`- rounds: ${arg.log.length}${last ? `, last on ${last.at}` : ''}`);
  out.push(`- warnings: ${warnings.length}`, '');

  const tree = outline(arg, a);
  out.push('## Structure', '', 'Status and id of each claim. Indented under a claim: what it rests on, then what is said against it.', '', ...tree.lines, '');

  if (a.cruxes.cruxes.length > 0) {
    out.push('## Disputes', '');
    const then = (s: string): string => (s === 'contested' ? 'stays contested' : s);
    for (const x of a.cruxes.cruxes) out.push(`- ${code(x.a)} against ${code(x.b)}: if ${code(x.a)} prevails the conclusion ${then(x.ifAPrevails)}; if ${code(x.b)} prevails it ${then(x.ifBPrevails)}`);
    out.push('');
  }

  out.push('## Bets, most exposed first', '', '| bet | trust | status | side | conclusion if it fails | other claims that change | sharp | evidence for / against |', '| --- | --- | --- | --- | --- | --- | --- | --- |');
  for (const b of a.bets) {
    const claim = arg.claims.get(b.id);
    const pro = claim?.evidence.filter((e) => e.stance === 'for').length ?? 0;
    out.push(`| ${code(b.id)} | ${b.trust} | ${b.status} | ${b.side} | ${b.decisive ? b.conclusionIfFails : 'unchanged'} | ${b.alsoChanges} | ${entry.res?.flags.has(b.id) ? 'no' : 'yes'} | ${pro} / ${(claim?.evidence.length ?? 0) - pro} |`);
  }
  out.push('');

  out.push('## Next steps, most valuable first', '', ...stepLines(nextSteps(arg, a)), '');

  const rest = [...arg.claims.keys()].filter((id) => !tree.order.includes(id));
  out.push('## Claims', '', `In the order of Structure.${rest.length > 0 ? ` The last ${rest.length} are not connected to the conclusion.` : ''} Text is as written in the file, so pinned terms appear as {key} or {key|shown words}. A claim with no review line has not been reviewed.`, '');
  for (const id of [...tree.order, ...rest]) {
    const claim = arg.claims.get(id);
    if (claim) out.push(...argumentClaim(arg, a, claim, entry.res));
  }

  if (arg.terms.size > 0) out.push('## Pinned terms', '', ...termLines(arg.terms.values(), arg.claims.values()), '');
  if (warnings.length > 0) out.push('## Warnings', '', ...warnings.map(issue), '');
  if (arg.log.length > 0) {
    out.push('## Rounds, oldest first', '');
    arg.log.forEach((e, i) => {
      const left = e.verdict ? ` Left: ${e.verdict}${e.bets !== undefined && e.sharp !== undefined ? `, ${e.sharp} of ${e.bets} bets sharp` : ''}.` : '';
      out.push(`${i + 1}. ${e.at} ${e.by} ${e.did}${e.claim ? ` ${code(e.claim)}` : ''}.${left}${e.note ? ` Note: ${one(e.note)}` : ''}`);
    });
    out.push('');
  }
  return out.join('\n');
}

/* ---------- The library and the index ---------- */

function libraryPage(root: string, library: RawFile[], entries: Entry[]): string {
  const out = ['# Claims library', '', `Claims any argument can rest on. No status is given here, because a status belongs to a claim inside an argument. ${built(root)}`, ''];
  if (library.length === 0) out.push('The library is empty.', '');
  for (const file of library) {
    out.push(`## ${file.name}`, '', `${count(file.claims.size, 'claim')}.`, '');
    const errors = file.issues.filter((i) => i.severity === 'error');
    if (errors.length > 0) out.push(...errors.map((i) => `- error [${i.code}]: ${one(i.message)}`), '');
    if (file.terms.size > 0) out.push('Pinned terms:', '', ...termLines(file.terms.values(), file.claims.values(), ' this file'), '');
    for (const claim of file.claims.values()) {
      const id = claim.id;
      const disputes = file.disputes.filter((pair) => pair.includes(id)).map(([x, y]) => (x === id ? y : x));
      const objectsTo = file.attacks.filter(([from]) => from === id).map(([, to]) => to);
      const objectedBy = file.attacks.filter(([, to]) => to === id).map(([from]) => from);
      const holdsUp = library.flatMap((f) => [...f.claims.values()]).filter((c) => c.because.some((g) => g.includes(id))).map((c) => c.id);
      const used = entries.flatMap((e) => {
        const there = e.loaded.argument?.claims.get(id);
        return there && there.origin !== '' ? [`${code(e.file)} (${e.analysis?.statuses.get(id) ?? 'not computed'} there)`] : [];
      });
      out.push(`### ${id}`, '', `- kind: ${claim.bet ? `bet, trust ${claim.bet.trust}, cost ${claim.bet.cost}` : 'supported'}`, `- text: ${one(claim.text)}`);
      if (claim.because.length > 0) out.push(`- rests on: ${support(claim)}`);
      if (holdsUp.length > 0) out.push(`- holds up: ${ids(holdsUp)}`);
      if (objectsTo.length > 0) out.push(`- objects to: ${ids(objectsTo)}`);
      if (objectedBy.length > 0) out.push(`- objected to by: ${ids(objectedBy)}`);
      if (disputes.length > 0) out.push(`- in dispute with: ${ids(disputes)}`);
      out.push(`- used in: ${used.length > 0 ? used.join(', ') : 'no argument'}`);
      if (claim.bet?.note) out.push(`- stops here because: ${one(claim.bet.note)}`);
      if (claim.note) out.push(`- note: ${one(claim.note)}`);
      out.push(...flagLines(claim.bet ? lintClaim(claim) : []), ...reviewLines(claim), ...evidenceLines(claim), ...testLines(claim), '');
    }
  }
  return out.join('\n');
}

/**
 * Whether the history behind this digest passes "argmap verify". Statuses are
 * worked out from the files as they stand, so a reader needs to know whether
 * those files got here by commits that verify refuses.
 */
function historyCheck(root: string): string[] {
  if (!isRepo(root) || tryGit(root, ['rev-parse', '--verify', '--quiet', 'HEAD']) === undefined) return [];
  if (tryGit(root, ['rev-parse', '--is-shallow-repository']) === 'true') {
    return ['Not run: this copy of the repository does not hold its full history, so the commits cannot be checked.'];
  }
  const signers = parseSigners(readSigners(root).text);
  if (signers.length === 0) return ['Not run: there is no list of trusted keys to check signatures against.'];
  let checks: ReturnType<typeof verifyRange>;
  try {
    checks = verifyRange(root, 'HEAD', signers);
  } catch {
    return ['Not run: the history could not be read.'];
  }
  const refused = checks.filter((c) => c.problems.length > 0);
  if (refused.length === 0) return [`All ${count(checks.length, 'commit')} pass ${code('argmap verify')}. Every status in this digest rests on history that verify accepts.`];
  return [
    `${refused.length} of ${count(checks.length, 'commit')} are refused by ${code('argmap verify')}. The statuses in this digest are worked out from the files as they stand, and those files include what these commits did:`,
    '',
    ...refused.slice(0, 20).map((c) => `- ${code(c.commit.slice(0, 7))} ${one(c.subject)}: ${one(c.problems[0] ?? '')}${c.problems.length > 1 ? ` (and ${c.problems.length - 1} more)` : ''}`),
    ...(refused.length > 20 ? [`- and ${refused.length - 20} more commits`] : []),
  ];
}

function indexPage(root: string, entries: Entry[], library: RawFile[]): string {
  const out = [
    '# argmap digest',
    '',
    `Everything in this repository that is computed or scattered, written out to be read in one pass. ${built(root)}`,
    '',
    '## How to read it',
    '',
    '- Every claim is named by its id, in backticks. Search for an id to find everything about it.',
    '- Statuses are stands, falls and contested. They follow from the bets as written; none of them means true.',
    '- A bet is a claim with no support: a place where justification stops. Its trust is observed, corroborated, track-record or assumed.',
    '- Claim text is as written in the source, so pinned terms appear as {key} or {key|shown words}.',
    '- A claim with no review line has not been reviewed.',
    '- Notepads are not here. They are plain Markdown on the `ideas` branch: `ideas/<argument file name>.md` and `ideas/claims/<claim id>.md`.',
    '',
  ];
  const history = historyCheck(root);
  if (history.length > 0) out.push('## History check', '', ...history, '');
  out.push('## Arguments', '');
  if (entries.length === 0) out.push('None yet.', '');
  for (const e of entries) {
    const arg = e.loaded.argument;
    const a = e.analysis;
    out.push(`### ${e.file}`, '', `- digest: ${code(e.page)}`);
    if (!arg || !a) {
      out.push(`- does not load: ${count(e.loaded.issues.filter((i) => i.severity === 'error').length, 'error')}`, '');
      continue;
    }
    const withEvidence = [...arg.claims.values()].filter((c) => c.evidence.length > 0);
    const steps = nextSteps(arg, a);
    out.push(
      `- title: ${one(arg.title)}`,
      `- conclusion: ${code(arg.conclusion)} is ${a.conclusion}`,
      `- text: ${one(arg.claims.get(arg.conclusion)?.text ?? '')}`,
      `- disputes: ${settlements(a)}`,
      ...(a.cruxes.cruxes.length > 0 ? [`- hinges on: ${a.cruxes.cruxes.map((x) => `${code(x.a)} against ${code(x.b)}`).join('; ')}`] : []),
      ...(a.cruxes.standsOnlyIf.length > 0 ? [`- it stands only if these prevail: ${ids(a.cruxes.standsOnlyIf)}`] : []),
      ...(steps.length > 0 ? [`- start with: ${steps.slice(0, 3).map((x) => `${x.kind} ${x.claims.map(code).join(' against ')}`).join(', ')} (${count(steps.length, 'step')} in all)`] : []),
      `- claims: ${arg.claims.size}, of which ${e.res?.bets ?? 0} are bets and ${e.res?.sharp ?? 0} of those are specific enough to check`,
      `- evidence: ${count(withEvidence.reduce((n, c) => n + c.evidence.length, 0), 'record')} on ${count(withEvidence.length, 'claim')}`,
      `- reviews: ${[...arg.claims.values()].filter((c) => reviewSummary(c).state !== 'unreviewed').length} of ${arg.claims.size} claims reviewed`,
      `- rounds: ${arg.log.length}${arg.log.length > 0 ? `, last on ${arg.log.at(-1)?.at}` : ''}`,
      `- warnings: ${e.loaded.issues.filter((i) => i.severity === 'warning').length}`,
      '',
    );
  }

  out.push('## Claims library', '', 'Digest: `claims.md`.', '');
  for (const file of library) out.push(`- ${code(file.name)}: ${ids([...file.claims.keys()])}`);
  if (library.length === 0) out.push('Empty.');
  out.push('');

  // What each name has on record. A library claim is counted once, from the library.
  const records = new Map<string, { reviews: number; evidence: number; rounds: number }>();
  const tally = (by: string | undefined, kind: 'reviews' | 'evidence' | 'rounds'): void => {
    if (!by) return;
    const row = records.get(by) ?? { reviews: 0, evidence: 0, rounds: 0 };
    row[kind]++;
    records.set(by, row);
  };
  const own = [...library.flatMap((f) => [...f.claims.values()]), ...entries.flatMap((e) => [...(e.loaded.argument?.claims.values() ?? [])].filter((c) => c.origin === ''))];
  for (const claim of own) {
    for (const r of claim.reviews) tally(r.by, 'reviews');
    for (const ev of claim.evidence) tally(ev.by, 'evidence');
  }
  for (const e of entries) for (const round of e.loaded.argument?.log ?? []) tally(round.by, 'rounds');
  const list = readSigners(root);
  const signers = parseSigners(list.text);
  const row = (name: string): string => {
    const r = records.get(name) ?? { reviews: 0, evidence: 0, rounds: 0 };
    return `${count(r.reviews, 'review')}, ${count(r.evidence, 'evidence record')}, ${count(r.rounds, 'round')}`;
  };
  const source = signers.length > 0 || !list.from.startsWith('nowhere') ? `read from ${code(list.from)}` : 'but there is no allowed_signers file';
  // What each name's predictions show. Scores are split by kind of prediction and never rolled into one number.
  const scored = nameRecords(allPredictions(root));
  out.push('## Records', '', 'What each name\'s predictions show. A record is split into lookups (the answer already existed) and forecasts by how long they ran, because skill at one says little about the other. It sits beside the trust labels and never sets one.', '');
  if (scored.length === 0) out.push('Nobody has set a prediction yet.', '');
  for (const r of scored) out.push('```', formatRecord(r), '```', '');

  out.push('## Trusted keys', '', `Who can put a judgment on record, ${source}. Record work under the name of the key that signs the commit.`, '');
  for (const s of signers) out.push(`- ${code(s.name)} (${s.kind === 'unknown' ? 'kind not stated' : s.kind})${s.label ? `, ${one(s.label)}` : ''}: ${row(s.name)}`);
  if (signers.length === 0) out.push('The list is empty, so no commit can be attributed to anyone.');
  const listed = new Set(signers.map((s) => s.name));
  const unlisted = [...records.keys()].filter((name) => !listed.has(name)).sort();
  for (const name of unlisted) out.push(`- ${code(name)} (no key on the list): ${row(name)}`);
  out.push('');
  return out.join('\n');
}

/**
 * The repository written out for reading as text, mainly by a model starting a
 * session: what the engine computes (statuses, what each dispute decides, how
 * exposed each bet is, what to do next) next to what the files say, with every
 * claim named by its id. Nothing here is a source: it is generated from the
 * argument files, the claims library and the list of trusted keys.
 */
export function buildDigest(root: string): DigestFile[] {
  const entries: Entry[] = argumentFiles(root).map((path) => {
    const file = slash(relative(root, path));
    const loaded = loadFile(path, root);
    const entry: Entry = { file, page: file.replace(/\.ya?ml$/, '.md'), loaded };
    if (loaded.ok && loaded.argument) {
      entry.analysis = analyze(loaded.argument);
      entry.res = resolution(loaded.argument);
    }
    return entry;
  });
  const library = libraryFiles(root).map((path) => parseFile(readFileSync(path, 'utf8'), slash(relative(root, path))));
  return [
    { path: 'README.md', content: indexPage(root, entries, library) },
    { path: 'claims.md', content: libraryPage(root, library, entries) },
    ...entries.map((entry) => ({ path: entry.page, content: argumentPage(root, entry) })),
  ];
}
